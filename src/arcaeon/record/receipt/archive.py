def _receipt_rows(report: dict) -> List[dict]:
    """One entry per receipt, verdict included, FAIL and undetermined with
    the rest. The row order is the report's, so the manifest and the CSV
    cannot disagree about what was in the class."""
    return [{"file": f"{COHORT_DIR}/{r['file']}",
             "receipt_id": r["receipt_id"],
             "trainee": r["trainee"],
             "verdict": r["verdict"],
             "ledger": r["ledger"],
             "anchor": r["anchor"],
             "reason": r["reason"]} for r in report["rows"]]


def build_manifest(report: dict, files: List[dict], *, source: str,
                   generated_at: str) -> dict:
    """What this archive is, what is in it, and what every file hashes to.

    `scope_proves` / `scope_does_not_prove` are the report header's own
    strings, which are read verbatim out of the receipts by
    `roster_report._scope_text`. Copied rather than restated so the manifest
    and the roster report cannot drift into two versions of the claim.
    """
    h = report["header"]
    counts = {"receipts": int(h["receipts_counted"]), OK: int(h["verified"]),
              FAIL: int(h["failed"]), UNDETERMINED: int(h["undetermined"])}
    return {
        "archive_version": ARCHIVE_VERSION,
        "generated_at": generated_at,
        "issuer": h["issuer"],
        "cohort": h["cohort"],
        "source": source,
        "scope_proves": h["scope_proves"],
        "scope_does_not_prove": h["scope_does_not_prove"],
        "verdict_counts": counts,
        "verification_passes": h["verification_passes"],
        "receipts": _receipt_rows(report),
        "digest_algorithm": "sha256 over the file's bytes, lowercase hex",
        "manifest_covers": ("every file in this archive except "
                            f"{MANIFEST_NAME} itself"),
        "files": files,
    }


def manifest_json(manifest: dict) -> str:
    return json.dumps(manifest, indent=1, ensure_ascii=False) + "\n"


def exit_code(manifest: dict) -> int:
    """0 / 2 / 4, the same three meanings as `verify --batch` and the roster
    report. The archive is written at every one of them: an export that
    refused to build because a receipt failed would hide the receipt the
    coordinator is looking for."""
    c = manifest["verdict_counts"]
    if c[FAIL]:
        return 2
    if c[UNDETERMINED]:
        return 4
    return 0


