def _write_zip(out: Path, entries: List[tuple]) -> None:
    """[(archive path, bytes)] -> one zip, deterministic bytes.

    Fixed date, fixed create_system, fixed order, deflate at the library
    default. Nothing here reads the clock or the filesystem's metadata.
    """
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        for arcname, data in entries:
            info = zipfile.ZipInfo(arcname, date_time=FIXED_ZIP_DATE)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.create_system = ZIP_CREATE_SYSTEM
            info.external_attr = 0o644 << 16
            z.writestr(info, data)


def _audit(out: Path, manifest: dict, sources: dict) -> None:
    """Read the finished archive back and prove every file survived the trip.

    Two comparisons, not one: each entry against the digest on the manifest,
    and each copied-in file against the bytes still on disk. The first catches
    a packing bug, the second catches a manifest that agrees with a file this
    module already altered.
    """
    with zipfile.ZipFile(out) as z:
        names = set(z.namelist())
        expected = {f["path"] for f in manifest["files"]} | {MANIFEST_NAME}
        if names != expected:
            missing, extra = sorted(expected - names), sorted(names - expected)
            raise ArchiveIntegrityError(
                f"archive contents do not match the manifest: missing "
                f"{missing}, unexpected {extra}")
        for entry in manifest["files"]:
            got = _sha256(z.read(entry["path"]))
            if got != entry["sha256"]:
                raise ArchiveIntegrityError(
                    f"{entry['path']} came out of the archive as {got}, the "
                    f"manifest says {entry['sha256']}")
            src = sources.get(entry["path"])
            if src is not None and _sha256(src.read_bytes()) != got:
                raise ArchiveIntegrityError(
                    f"{entry['path']} is not byte-identical to its source "
                    f"{src}: a receipt was altered on the way into the archive")


def build_archive(target: str | Path, out: str | Path, *,
                  ledger_path: Optional[str | Path] = None, ots: bool = False,
                  generated_at: Optional[str] = None) -> dict:
    """Build the archive at `out`, return its manifest.

    One clock reading, taken here and handed to both the roster report and
    the manifest, so the two documents in the archive agree about when it was
    made and so two runs differ in exactly one value.
    """
    stamp = generated_at or _now()
    pairs = gather(target, ledger_path=ledger_path)
    report = roster_report.build_report(target, ledger_path=ledger_path, ots=ots,
                                        generated_at=stamp)

    packed = {arc: src.read_bytes() for arc, src in pairs}
    sources = {arc: src for arc, src in pairs}

    # the report's rows and the copied receipts must be the same set of files,
    # or the manifest is describing a class the archive does not hold
    reported = {f"{COHORT_DIR}/{r['file']}" for r in report["rows"]}
    if not reported <= set(packed):
        raise ArchiveIntegrityError(
            "the roster report covers receipts the archive does not hold: "
            f"{sorted(reported - set(packed))}")

    roster_csv = roster_report.to_csv(report).encode("utf-8")
    body = [(ROSTER_NAME, roster_csv)] + [(arc, packed[arc]) for arc, _ in pairs]

    files = [{"path": arc, "bytes": len(data), "sha256": _sha256(data)}
             for arc, data in body]
    manifest = build_manifest(report, files, source=str(target), generated_at=stamp)

    # The README is written FROM the manifest (it quotes the scope block and
    # the verdict counts), so its digest cannot be known until the manifest
    # exists. Built here, then listed in the same file table as everything
    # else -- the manifest covers every file in the archive but itself, and a
    # README left out of that table would be the one file nobody could check.
    readme = readme_text(manifest).encode("utf-8")
    manifest["files"] = files + [{"path": README_NAME, "bytes": len(readme),
                                  "sha256": _sha256(readme)}]

    entries = [(README_NAME, readme), (MANIFEST_NAME, manifest_json(manifest).encode("utf-8"))]
    entries += body

    out = Path(out)
    _write_zip(out, entries)
    _audit(out, manifest, sources)
    return manifest


def summary_line(manifest: dict, out: str | Path) -> str:
    c = manifest["verdict_counts"]
    n = c["receipts"]
    return (f"{n} receipt{'s' if n != 1 else ''}: {c[OK]} VERIFIED, {c[FAIL]} BROKEN, "
            f"{c[UNDETERMINED]} COULD NOT LOOK; {len(manifest['files']) + 1} files "
            f"in {Path(out).name}")
