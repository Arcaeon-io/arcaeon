def _ledger_files(receipt_paths: List[Path],
                  explicit: Optional[str | Path]) -> List[Path]:
    """Every ledger a receipt in this batch names, plus its witness sidecar.

    Resolution is `verify_batch.resolve_ledger`'s, not a second rule written
    here: the archive must bundle the file the verifier will go looking for,
    and the only way to be sure of that is to ask the verifier.
    """
    out: List[Path] = []
    seen = set()
    for p in receipt_paths:
        try:
            rc = json.loads(p.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue          # already an `undetermined` row; not a crash here
        if not isinstance(rc, dict):
            continue
        led, _ = verify_batch.resolve_ledger(rc, p, explicit)
        if led is None:
            continue
        for cand in (led, Path(str(led) + WITNESS_SUFFIX)):
            key = str(cand.resolve()).lower()
            if cand.exists() and cand.is_file() and key not in seen:
                seen.add(key)
                out.append(cand)
    return out


def _exhibit_of(receipt_path: Path) -> Optional[Path]:
    """The human-readable half of the pair, if the vendor kept it.

    `<name>.receipt.json` -> `<name>.exhibit.txt`, the pair `ballot` and
    `cite` write. The exhibit is what a hiring manager actually reads, and
    2.5 promises it inside the export; it is optional here because an export
    directory that holds only receipts is still a valid export.
    """
    name = receipt_path.name
    if not name.endswith(RECEIPT_SUFFIX):
        return None
    cand = receipt_path.with_name(name[:-len(RECEIPT_SUFFIX)] + EXHIBIT_SUFFIX)
    return cand if cand.exists() else None


def gather(target: str | Path, *, ledger_path: Optional[str | Path] = None) -> List[tuple]:
    """[(archive path, source path)] for everything copied in verbatim.

    Ordered: receipts first (the thing being proved), then exhibits, then
    ledgers and their sidecars, each group sorted by archive path. Fixed
    order is half of the determinism guarantee; the other half is the fixed
    timestamp at write time.
    """
    receipts, from_target = roster_report.resolve_target(target)
    if not receipts:
        raise verify_batch.NoReceiptsFound(
            f"no receipts under {target}: an archive is built from a cohort "
            f"directory of {verify_batch.RECEIPT_GLOB} files, or from the "
            "class ledger sitting beside them"
        )
    led = ledger_path if ledger_path is not None else from_target

    pairs: List[tuple] = []
    for p in receipts:
        pairs.append((f"{COHORT_DIR}/{p.name}", p))
    exhibits = [_exhibit_of(p) for p in receipts]
    for ex in sorted((e for e in exhibits if e is not None), key=lambda p: p.name):
        pairs.append((f"{COHORT_DIR}/{ex.name}", ex))
    for lp in sorted(_ledger_files(receipts, led), key=lambda p: p.name):
        pairs.append((f"{COHORT_DIR}/{lp.name}", lp))

    by_path = {}
    for arc, src in pairs:           # a name collision would silently drop a file
        if arc in by_path and by_path[arc].resolve() != src.resolve():
            raise ValueError(
                f"two different files would both be archived as {arc}: "
                f"{by_path[arc]} and {src}"
            )
        by_path[arc] = src
    return [(arc, by_path[arc]) for arc in sorted(by_path)]


