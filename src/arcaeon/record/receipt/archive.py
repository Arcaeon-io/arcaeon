"""Bulk export: one portable file a coordinator can hand to a stranger.

VENDOR_PACKAGE_SPEC 2.5, the half that was still unbuilt. The other half
landed in 4033305: bulk verification answers over a class in one pass. This
is the archive itself, and what it is for is the sentence in 2.5 -- the
class "in a form they own and can hand to anybody, including us going
away." An export that only works while we are still here is not an export.

WHAT GOES IN, AND WHY THAT SHAPE.

    MANIFEST.json        what this archive is, what is in it, each file's
                         sha256, the verdict of every receipt, and the scope
                         block verbatim
    README.txt           how a human with no tools checks it
    roster_report.csv    the coordinator's own page (roster_report.py, not
                         reimplemented here)
    cohort/              the export, byte for byte: every receipt, every
                         exhibit, the ledger files those receipts name, and
                         the witness sidecars beside them

Everything under `cohort/` is a byte-identical copy of what the vendor
already holds. Everything at the root is generated by this command. The
split is so a reader can tell at a glance which files we made and which
files we only moved.

`cohort/` is FLAT, and that is load-bearing rather than tidy: a receipt
finds its ledger by looking for that filename beside itself
(`verify_batch.resolve_ledger`, basename only), which is the shape an
export directory already has. Sorting receipts into `receipts/` and ledgers
into `ledger/` would make every extracted receipt come back `undetermined`
for want of a ledger nobody could find. The archive extracts into the shape
the verifier already knows.

THE WHOLE LEDGER FILE, NOT THE ROWS. A hash chain cannot be subset. The
verifier walks the file from its first row (`arcaeon_ledger.verify_file`),
so a ledger holding only the rows this class references would fail its own
chain check and every receipt in the archive would read `FAIL` for a reason
that is an artifact of the packing. The referenced rows arrive inside the
file that makes them checkable.

NOTHING IS MUTATED ON THE WAY IN. Receipts are copied as bytes and their
sha256 is recomputed from the archive after it is written, before this
function returns. A re-serialized receipt -- same values, different key
order or indentation -- verifies fine and is still the wrong thing to ship:
the archive is evidence, and evidence that was rewritten in transit invites
the one question the whole product exists to close.

A FAIL IS PACKED. A receipt that does not verify goes in with its verdict
on the manifest, next to the ones that do. Dropping it would make the
archive a curated exhibit instead of a record, and the coordinator running
this is looking for exactly that receipt. The exit code says a FAIL is in
there (2), or that something could not be determined (4); the archive is
written either way.

NO AGGREGATE ABOUT SCORES. Same rule as the roster report, for the same
reason quoted there: the scope block denies "the score is correct", and an
average, a rate, or an ordering asserts its opposite by arithmetic. The
counts in this manifest are VERDICT counts -- how many receipts verify --
and never a statistic about what the grading engine returned. A grep over a
real archive holds it.

THE CAP PAGES, IT DOES NOT REFUSE. Verification here runs through
`roster_report.build_report`, which pages in runs of the published 20 and
prints its own pass structure. `roster_report.py`'s docstring carries the
argument and the honest counter-argument; this module takes the same
position for the same reason, and would move with it if the cap is ever
re-read as a commercial limit rather than the anti-truncation rule it is
written as.

DETERMINISTIC. The same cohort archived twice produces byte-identical zip
files apart from `generated_at`: entries are written in a fixed order, with
a fixed timestamp (zip files otherwise stamp the wall clock into every
entry header) and a fixed create_system, and the one clock reading is taken
once and shared by the manifest and the roster report. Two archives of the
same class that differ in bytes make a reader ask which one is the real
one, and there is no good answer to that question.
"""
from __future__ import annotations

import hashlib
import json
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Optional

from . import roster_report, verify_batch
from .verify_batch import FAIL, OK, UNDETERMINED

ARCHIVE_VERSION = "arcaeon-receipt-archive/1"

MANIFEST_NAME = "MANIFEST.json"
README_NAME = "README.txt"
ROSTER_NAME = "roster_report.csv"
COHORT_DIR = "cohort"

#: Every zip entry is stamped with this instead of the wall clock. 1980-01-01
#: is the zero of the DOS timestamp the format stores, so it is the one value
#: that survives a round trip through every unzip tool unchanged.
FIXED_ZIP_DATE = (1980, 1, 1, 0, 0, 0)

#: Written into every entry header so an archive built on Windows and one
#: built on Linux from the same cohort are the same bytes. 3 is Unix.
ZIP_CREATE_SYSTEM = 3

#: Where a stranger goes to check this without installing anything. Until
#: 2026-09-23 this named `web/verify-receipt.html` in a GitHub repo
#: (github.com/Arcaeon-io/arcaeon-receipt) that does not exist publicly: the
#: URL returned 404 on 2026-09-23, so every archive's README sent its reader
#: to a dead link. The hosted page is now live: https://arcaeon.io/verify-receipt
#: returned 200 on 2026-09-23 and its bytes equal the site's source copy, which
#: passes the parity test (verbatim `web/verify-receipt.html` plus two marked
#: chrome blocks, no external `src`/`href`, no fetch). It runs entirely in the
#: reader's browser and calls nothing, so a saved copy is the same verifier.
VERIFIER_PAGE_URL = "https://arcaeon.io/verify-receipt"

EXHIBIT_SUFFIX = ".exhibit.txt"
RECEIPT_SUFFIX = ".receipt.json"
WITNESS_SUFFIX = ".witness.jsonl"


class ArchiveIntegrityError(RuntimeError):
    """A file did not come out of the finished archive as the bytes that went
    in. Raised after writing and before returning, so a caller never gets a
    success line over an archive whose contents moved."""


def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


